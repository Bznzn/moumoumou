test('closing the only setup window leaves the menu-bar application alive',async()=>{
  const directory=await mkdtemp(path.join(tmpdir(),'salary-float-lifecycle-'));
  let application:Awaited<ReturnType<typeof electron.launch>>|undefined;
  try{
    application=await electron.launch({executablePath:executable,env:{...process.env,SALARY_FLOAT_USER_DATA:directory,SALARY_FLOAT_TEST_MODE:'1'},timeout:30000});
    const settings=await application.firstWindow();await expect(settings.getByLabel('月薪（元）')).toBeAttached();await settings.close();
    expect(await application.evaluate(({app})=>new Promise<boolean>(resolve=>setTimeout(()=>resolve(app.isReady()),250)))).toBe(true);
    const reopened=application.waitForEvent('window');await application.evaluate(({app})=>{app.emit('second-instance',{},[],process.cwd());});
    await expect((await reopened).getByLabel('月薪（元）')).toBeAttached();
  }finally{await application?.close().catch(()=>{});await rm(directory,{recursive:true,force:true});}
});
