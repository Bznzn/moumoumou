import{test,expect,_electron as electron}from'@playwright/test';
import{mkdtemp,rm,readFile,mkdir}from'node:fs/promises';
import{tmpdir}from'node:os';
import path from'node:path';
import{execFileSync}from'node:child_process';
const executable=process.env.SALARY_FLOAT_EXECUTABLE??path.resolve('release/mac-arm64/牛马冲冲冲.app/Contents/MacOS/牛马冲冲冲');
test('packaged application has a valid signature matching its bundle identity',()=>{
  const bundle=path.resolve(executable,'../../..');
  execFileSync('/usr/bin/codesign',['--verify','--deep','--strict',bundle]);
  const metadata=execFileSync('/usr/libexec/PlistBuddy',['-c','Print CFBundleIdentifier',path.join(bundle,'Contents/Info.plist')],{encoding:'utf8'}).trim();
  expect(metadata).toBe('com.moumoumou.salaryfloat');
  execFileSync('/usr/bin/codesign',['--verify','--strict',`-R=identifier "${metadata}"`,bundle]);
});
